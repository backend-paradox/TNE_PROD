// Transform trips to add missing fields for component compatibility
const enrichTrip = (trip: Trip): Trip => ({
  ...trip,
  overview: trip.overview || trip.shortDescription || trip.description.substring(0, 200),
  isPopular: trip.isPopular ?? trip.popular,
  tags: trip.tags || [
    trip.category.toLowerCase(),
    ...trip.tripType.map(t => t.toLowerCase()),
    trip.destination.toLowerCase()
  ].slice(0, 5)
});

// Export enriched trips data
export const enrichedTripsData = tripsData.map(enrichTrip);

export const getTripsbyCategory = (category: string): Trip[] => enrichedTripsData.filter(trip => trip.category === category);
export const getFeaturedTrips = (): Trip[] => enrichedTripsData.filter(trip => trip.featured);
export const getPopularTrips = (): Trip[] => enrichedTripsData.filter(trip => trip.popular);
export const getNewArrivals = (): Trip[] => enrichedTripsData.filter(trip => trip.newArrival);
export const getTripBySlug = (slug: string): Trip | undefined => enrichedTripsData.find(trip => trip.slug === slug);
export const getTripById = (id: string): Trip | undefined => enrichedTripsData.find(trip => trip.id === id);
export const searchTrips = (query: string): Trip[] => {
  const lowerQuery = query.toLowerCase();
  return enrichedTripsData.filter(trip => 
    trip.title.toLowerCase().includes(lowerQuery) ||
    trip.destination.toLowerCase().includes(lowerQuery) ||
    trip.country.toLowerCase().includes(lowerQuery)
  );
};
